/**************************************************************************************
 * helix_port.h - replacement of real/assembly.h for the RP2040 / RP2350 benchmark
 *
 * Force-included (-include helix_port.h) before every Helix source file. It defines the
 * _ASSEMBLY_H guard, so the original real/assembly.h (whose GCC/ARM block is ARM-mode only
 * and incomplete) is skipped and the submodule stays unmodified.
 *
 * HELIX_PORT_MODE selects the implementation of the 64-bit multiply helpers:
 *   HELIX_PORT_C64    generic C: (Word64)x * y. On ARMv6-M (Cortex-M0+, RP2040) GCC calls
 *                     __aeabi_lmul (64x64 multiply, pico_int64_ops)
 *   HELIX_PORT_M0     generic C as well, but MULSHIFT32/MADD64 from four 16x16->32 multiplies
 *                     (MULS is single-cycle on RP2040), no 64x64 helper call
 *   HELIX_PORT_DSP    ARMv7E-M / ARMv8-M Main with DSP extension (Cortex-M33, RP2350):
 *                     SMMUL for MULSHIFT32, SMLAL (generated by GCC) for MADD64, CLZ
 * All three give bit-identical results (MULSHIFT32 is the floor of the 64-bit product >> 32).
 **************************************************************************************/

#ifndef _ASSEMBLY_H
#define _ASSEMBLY_H

#define HELIX_PORT_C64 1
#define HELIX_PORT_M0  2
#define HELIX_PORT_DSP 3

#ifndef HELIX_PORT_MODE
#if defined(__ARM_FEATURE_DSP)
#define HELIX_PORT_MODE HELIX_PORT_DSP
#elif defined(__ARM_ARCH_6M__)
#define HELIX_PORT_MODE HELIX_PORT_M0
#else
#define HELIX_PORT_MODE HELIX_PORT_C64
#endif
#endif

typedef long long Word64;

/* benchmark: count the decoder's heap use (only real/buffers.c allocates) */
#ifdef HELIX_BENCH_MALLOC
#include <stddef.h>
void* bench_malloc(size_t size);
#define malloc(size) bench_malloc(size)
#endif

#if HELIX_PORT_MODE == HELIX_PORT_DSP

static __inline int MULSHIFT32(int x, int y)
{
    int z;
    __asm__ ("smmul %0, %1, %2" : "=r" (z) : "r" (x), "r" (y));
    return z;
}

static __inline Word64 MADD64(Word64 sum, int x, int y)
{
    return sum + (Word64)x * (Word64)y;  /* SMLAL */
}

static __inline int CLZ(int x)
{
    int n;
    __asm__ ("clz %0, %1" : "=r" (n) : "r" (x));  /* CLZ of 0 is 32 */
    return n;
}

#elif HELIX_PORT_MODE == HELIX_PORT_M0

/* x = xh * 2^16 + xl, xh signed 16 bit, xl unsigned 16 bit (same for y) */
static __inline int MULSHIFT32(int x, int y)
{
    int xh = x >> 16, yh = y >> 16;
    unsigned int xl = (unsigned int)x & 0xffffu, yl = (unsigned int)y & 0xffffu;
    unsigned int ll = xl * yl;
    int hl = xh * (int)yl;   /* |hl| < 2^31 */
    int lh = (int)xl * yh;
    unsigned int mid = (ll >> 16) + ((unsigned int)hl & 0xffffu) + ((unsigned int)lh & 0xffffu);
    return xh * yh + (hl >> 16) + (lh >> 16) + (int)(mid >> 16);
}

static __inline Word64 MADD64(Word64 sum, int x, int y)
{
    int xh = x >> 16, yh = y >> 16;
    unsigned int xl = (unsigned int)x & 0xffffu, yl = (unsigned int)y & 0xffffu;
    unsigned int ll = xl * yl;
    int hl = xh * (int)yl;
    int lh = (int)xl * yh;
    unsigned int mid = (ll >> 16) + ((unsigned int)hl & 0xffffu) + ((unsigned int)lh & 0xffffu);
    unsigned int lo = (ll & 0xffffu) | (mid << 16);
    int hi = xh * yh + (hl >> 16) + (lh >> 16) + (int)(mid >> 16);
    return sum + (Word64)(((unsigned long long)(unsigned int)hi << 32) | lo);
}

static __inline int CLZ(int x)
{
    return x ? __builtin_clz((unsigned int)x) : 32;
}

#else /* HELIX_PORT_C64 */

static __inline int MULSHIFT32(int x, int y)
{
    return (int)(((Word64)x * (Word64)y) >> 32);
}

static __inline Word64 MADD64(Word64 sum, int x, int y)
{
    return sum + (Word64)x * (Word64)y;
}

static __inline int CLZ(int x)
{
    return x ? __builtin_clz((unsigned int)x) : 32;
}

#endif

static __inline int FASTABS(int x)
{
    int sign = x >> (sizeof(int) * 8 - 1);
    return (x ^ sign) - sign;
}

static __inline Word64 SHL64(Word64 x, int n)
{
    return (Word64)((unsigned long long)x << n);
}

static __inline Word64 SAR64(Word64 x, int n)
{
    return x >> n;
}

#endif /* _ASSEMBLY_H */
